import type { ParamValues, RunRecord, SimulationModel } from '../engine/types';
import type { ExperimentDef } from '../experiments/types';
import { EXPERIMENTS, PLANNED } from '../experiments/catalog';
import { formatNumber, formatQuantity, formatTime, unitSymbol } from '../engine/units';
import { paramsTable } from '../lib/export';

export interface AssistantRun {
  label: string;
  model: SimulationModel;
  record: RunRecord;
}

export interface AssistantContext {
  model: SimulationModel | null;
  question: string;
  experiment: ExperimentDef | null;
  params: ParamValues | null;
  currentParams?: ParamValues | null;
  record: RunRecord | null;
  baseline: RunRecord | null;
  baselineLabel?: string;
  status?: string;
  time?: number;
  /** Extra runs, e.g. from the comparison page. */
  runs?: AssistantRun[];
}

/** Stable catalog description for the system prompt (cacheable). */
export function catalogDigest(): string {
  const impl = EXPERIMENTS.map((e) => `- ${e.id}: ${e.title} [model ${e.modelId}, ${e.category}]`).join('\n');
  const planned = PLANNED.map((p) => `- ${p.id}: ${p.title} [planned — not simulated]`).join('\n');
  return `Implemented experiments (only these can be run):\n${impl}\n\nPlanned scenarios (not simulated; overview only):\n${planned}`;
}

function series(model: SimulationModel, run: RunRecord, keys: string[], points = 24): string {
  const n = run.samples.t.length;
  if (!n) return '';
  const step = Math.max(1, Math.floor(n / points));
  const cols = keys.filter((k) => run.samples.obs[k] && !run.samples.obs[k].every((v) => Number.isNaN(v)));
  if (!cols.length) return '';
  const head = ['t', ...cols].join(' | ');
  const rows: string[] = [];
  for (let i = 0; i < n; i += step) rows.push([formatNumber(run.samples.t[i], 4), ...cols.map((k) => formatNumber(run.samples.obs[k][i], 4))].join(' | '));
  const units = cols.map((k) => `${k} in ${unitSymbol(model.observables.find((o) => o.key === k)!.unit) || 'dimensionless'}`).join(', ');
  return `Sampled series (t in ${unitSymbol(model.time.unit) || model.time.unit}; ${units}):\n${head}\n${rows.join('\n')}`;
}

function describeRun(model: SimulationModel, run: RunRecord, label: string): string {
  const lines: string[] = [];
  lines.push(`### ${label}`);
  lines.push('Parameters: ' + paramsTable(model, run.params).map((r) => `${r.label} = ${r.value}`).join('; '));
  lines.push(`Simulated span: ${formatTime(run.samples.t.at(-1) ?? 0, model.time.unit)} of ${formatTime(run.duration, model.time.unit)} (${run.numerics.stoppedReason})`);
  const key = model.summarize?.(run) ?? [];
  if (key.length)
    lines.push(
      'Key results (from the recorded run): ' +
        key.map((k) => `${k.label} = ${typeof k.value === 'number' ? (k.unit ? formatQuantity(k.value, k.unit, { sig: k.sig ?? 4 }) : formatNumber(k.value, 4)) : k.value} [${k.provenance}]`).join('; '),
    );
  lines.push(
    'Final values: ' +
      model.observables
        .filter((o) => run.final[o.key] !== undefined && !Number.isNaN(run.final[o.key]))
        .map((o) => `${o.label} = ${formatQuantity(run.final[o.key], o.unit, { sig: 4 })} [${o.provenance}]`)
        .join('; '),
  );
  const evs = run.events.filter((e) => !(e.source === 'user' && e.severity === 'info')).slice(0, 40);
  if (evs.length) lines.push('Events:\n' + evs.map((e) => `- ${formatTime(e.t, model.time.unit)}: ${e.label}${e.detail ? ` — ${e.detail}` : ''}`).join('\n'));
  const keys = model.primaryObservables ?? model.observables.filter((o) => o.chart).map((o) => o.key);
  const s = series(model, run, keys.slice(0, 4));
  if (s) lines.push(s);
  return lines.join('\n');
}

/** The data block attached to each user message. Everything the assistant may state as a result is in here. */
export function buildContextBlock(ctx: AssistantContext): string {
  const parts: string[] = [];
  parts.push('[CURRENT LAB CONTEXT — generated by the app from actual model state]');
  if (!ctx.model) {
    parts.push('The user is not in an experiment right now.');
    return parts.join('\n');
  }
  const m = ctx.model;
  parts.push(`Question: ${ctx.question}`);
  parts.push(`Model: ${m.name} (${m.id}) — ${m.summary}`);
  if (ctx.experiment?.assumptions?.length) parts.push('How the question is interpreted:\n' + ctx.experiment.assumptions.map((a) => `- ${a}`).join('\n'));
  parts.push('Model assumptions:\n' + m.assumptions.map((a) => `- (${a.kind}) ${a.text}`).join('\n'));
  parts.push('Equations:\n' + m.equations.map((e) => `- ${e.label}: ${e.formula}`).join('\n'));
  parts.push('Limitations:\n' + m.limitations.map((l) => `- ${l}`).join('\n'));
  if (ctx.params) {
    const derived = m.derived?.(ctx.currentParams ?? ctx.params) ?? [];
    if (derived.length) parts.push('Closed-form quantities for the current settings: ' + derived.map((d) => `${d.label} = ${Number.isFinite(d.value) ? formatQuantity(d.value, d.unit, { sig: 4 }) : 'n/a'} [${d.provenance}]`).join('; '));
    const warn = m.warnings?.(ctx.currentParams ?? ctx.params) ?? [];
    if (warn.length) parts.push('Validity warnings: ' + warn.map((w) => w.message).join(' '));
  }
  if (ctx.record) parts.push(describeRun(m, ctx.record, `Recorded run (status: ${ctx.status ?? 'unknown'})`));
  else if (!ctx.runs?.length) parts.push(`No run has been recorded yet with the current settings (${ctx.params ? paramsTable(m, ctx.params).map((r) => `${r.label} = ${r.value}`).join('; ') : 'defaults'}). Do not state results for it.`);
  if (ctx.baseline) parts.push(describeRun(m, ctx.baseline, `Baseline run (${ctx.baselineLabel ?? 'baseline'})`));
  for (const r of ctx.runs ?? []) parts.push(describeRun(r.model, r.record, r.label));
  parts.push('[END CONTEXT]');
  return parts.join('\n\n');
}

export const SYSTEM_PROMPT = `You are the scientific assistant inside WHAT IF LAB, an app where people explore hypothetical scenarios with real, documented simulation models.

Your job: explain the science behind a scenario, explain equations in accessible language, interpret graphs and results, identify important assumptions, suggest parameters or follow-up experiments, compare runs, and help users phrase scenarios that fit an existing model.

Scientific integrity rules — follow them strictly:
1. Never invent simulation results. Numbers you present as results of the user's runs must come from the [CURRENT LAB CONTEXT] block in the conversation. If a result is not there, say the user needs to run (or re-run) the experiment and offer to explain what to look for.
2. Label what kind of statement you are making, using these tags in plain words: "Established science:", "From your simulation:", "Approximate estimate:", "Speculative:". Keep the tags short and natural.
3. When the scenario involves complex systems (climate, ecosystems, societies, physiology), explain the uncertainty and what the model leaves out. Point to the model's stated assumptions and limitations.
4. Only suggest experiments that exist in the catalog below, by their title; mention planned scenarios only as "planned — not simulated yet".
5. Do not present simplified models as complete descriptions of reality.
6. Be concise and concrete. Use short paragraphs or brief lists. Show equations in plain text/Unicode (e.g. v = √(2gh)). Use metric units unless asked otherwise.

`;

export function systemPrompt(): string {
  return SYSTEM_PROMPT + catalogDigest();
}
