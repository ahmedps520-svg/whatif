import type { ParamValues, RunRecord, SimulationModel } from '../engine/types';
import { formatNumber, formatQuantity, formatTime, unitSymbol } from '../engine/units';

export function download(filename: string, content: string, type = 'application/json') {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function slug(s: string): string {
  return (
    s
      .toLowerCase()
      .replace(/[’']/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 60) || 'experiment'
  );
}

function csvCell(v: unknown): string {
  const s = typeof v === 'number' ? (Number.isFinite(v) ? String(v) : '') : String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** Recorded samples as CSV with units in the header. */
export function runToCsv(model: SimulationModel, run: RunRecord): string {
  const cols = model.observables.filter((o) => run.samples.obs[o.key]);
  const header = [`t (${unitSymbol(model.time.unit) || model.time.unit})`, ...cols.map((o) => `${o.label}${unitSymbol(o.unit) ? ` (${unitSymbol(o.unit)})` : ''} [${o.provenance}]`)];
  const lines = [header.map(csvCell).join(',')];
  for (let i = 0; i < run.samples.t.length; i++) {
    lines.push([run.samples.t[i], ...cols.map((o) => run.samples.obs[o.key][i])].map(csvCell).join(','));
  }
  return lines.join('\n');
}

export function eventsToCsv(model: SimulationModel, run: RunRecord): string {
  const lines = [[`t (${unitSymbol(model.time.unit) || model.time.unit})`, 'severity', 'event', 'detail'].join(',')];
  for (const e of run.events) lines.push([e.t, e.severity, e.label, e.detail ?? ''].map(csvCell).join(','));
  return lines.join('\n');
}

export function paramsTable(model: SimulationModel, params: ParamValues): { label: string; value: string }[] {
  return model.params
    .filter((p) => !p.visibleWhen || p.visibleWhen(params))
    .map((p) => {
      const v = params[p.key];
      let value: string;
      if (p.type === 'number') value = formatQuantity(Number(v), p.unit, { sig: 4 });
      else if (p.type === 'choice') value = p.options.find((o) => o.value === v)?.label ?? String(v);
      else value = v ? 'On' : 'Off';
      return { label: p.label, value };
    });
}

/** A self-contained Markdown summary for notes, lessons or reports. */
export function runToMarkdown(opts: {
  model: SimulationModel;
  question: string;
  run: RunRecord | null;
  baseline?: RunRecord | null;
  baselineLabel?: string;
  experimentAssumptions?: string[];
  notes?: string;
  includeEducation?: boolean;
  level?: 'beginner' | 'intermediate' | 'advanced';
}): string {
  const { model, question, run, baseline } = opts;
  const out: string[] = [];
  out.push(`# ${question}`, '');
  out.push(`*Model:* ${model.name} — ${model.summary}`, '');
  out.push(`*Generated by WHAT IF LAB on ${new Date().toISOString().slice(0, 10)}. Every number below comes from the model's own calculation unless marked otherwise.*`, '');
  if (run) {
    out.push('## Parameters', '', '| Parameter | Value |', '|---|---|');
    for (const r of paramsTable(model, run.params)) out.push(`| ${r.label} | ${r.value} |`);
    out.push('');
    if (baseline) {
      out.push(`## Baseline (${opts.baselineLabel ?? 'baseline'})`, '', '| Parameter | Value |', '|---|---|');
      for (const r of paramsTable(model, baseline.params)) out.push(`| ${r.label} | ${r.value} |`);
      out.push('');
    }
    const results = model.summarize?.(run) ?? [];
    if (results.length) {
      out.push('## Key results', '', '| Result | Value | Source |', '|---|---|---|');
      for (const r of results) {
        const v = typeof r.value === 'number' ? (r.unit ? formatQuantity(r.value, r.unit, { sig: r.sig ?? 3 }) : formatNumber(r.value, r.sig ?? 3)) : r.value;
        out.push(`| ${r.label} | ${v} | ${r.provenance} |`);
      }
      out.push('');
    }
    out.push('## Final state', '', '| Quantity | Value' + (baseline ? ' | Baseline' : '') + ' |', '|---|---|' + (baseline ? '---|' : ''));
    for (const o of model.observables) {
      const v = run.final[o.key];
      if (v === undefined || Number.isNaN(v)) continue;
      const b = baseline?.final[o.key];
      out.push(`| ${o.label} | ${formatQuantity(v, o.unit, { sig: 4 })}` + (baseline ? ` | ${b === undefined || Number.isNaN(b) ? '—' : formatQuantity(b, o.unit, { sig: 4 })}` : '') + ' |');
    }
    out.push('');
    if (run.events.length) {
      out.push('## Timeline of events', '');
      for (const e of run.events.filter((x) => x.source !== 'user' || x.severity !== 'info')) out.push(`- **${formatTime(e.t, model.time.unit)}** — ${e.label}${e.detail ? `: ${e.detail}` : ''}`);
      out.push('');
    }
    out.push(`*Numerics:* ${run.numerics.steps.toLocaleString()} steps of ${formatNumber(run.numerics.dt, 3)} ${unitSymbol(model.time.unit)}; ${run.numerics.stoppedReason}`, '');
  }
  if (opts.experimentAssumptions?.length) {
    out.push('## How the question is interpreted', '');
    for (const a of opts.experimentAssumptions) out.push(`- ${a}`);
    out.push('');
  }
  out.push('## Assumptions', '');
  for (const a of model.assumptions) out.push(`- *(${a.kind})* ${a.text}`);
  out.push('', '## Equations', '');
  for (const e of model.equations) out.push(`- **${e.label}:** \`${e.formula}\` — ${e.explanation}`);
  out.push('', '## Limitations', '');
  for (const l of model.limitations) out.push(`- ${l}`);
  out.push('');
  if (model.dataSources?.length) {
    out.push('## Data sources', '');
    for (const d of model.dataSources) out.push(`- ${d.name} — ${d.provider}. ${d.citation} (${d.url}). ${d.license}`);
    out.push('');
  }
  if (opts.includeEducation) {
    const ed = model.education;
    out.push('## Learning objectives', '');
    for (const o of ed.objectives) out.push(`- ${o}`);
    out.push('', '## Background', '', ed.background[opts.level ?? 'intermediate'], '', '## Guided steps', '');
    ed.guidedSteps.forEach((s, i) => out.push(`${i + 1}. ${s}`));
    out.push('', '## Questions to consider', '');
    for (const q of ed.questions) out.push(`- ${q}`);
    out.push('');
  }
  if (opts.notes) out.push('## Notes', '', opts.notes, '');
  return out.join('\n');
}
